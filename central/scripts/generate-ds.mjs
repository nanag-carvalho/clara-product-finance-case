import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { designSystem as ds } from '../src/design-system/registry.ts'

const root = fileURLToPath(new URL('../', import.meta.url))
const args = new Set(process.argv.slice(2))
const checking = args.has('--check')
const defaultFont = ds.fonts.find(font=>font.id===ds.defaultFont)
const fontFaces = ds.fonts.flatMap(font=>font.files.map((file,index)=>`@font-face{font-family:'${font.cssFamily}';font-style:normal;font-display:swap;font-weight:${Array.isArray(font.weights)?font.weights[index]:font.weights};src:url('${file}') format('woff2')}`)).join('\n')
const rootValues = [
  `--font-sans:${defaultFont.family};`,
  ...Object.entries(ds.typography).flatMap(([name,type])=>[`--text-${name}:${type.size}px;`,`--leading-${name}:${type.lineHeight}px;`,`--weight-${name}:${type.weight};`]),
  ...Object.entries(ds.controlSizes).map(([name,value])=>`--control-${name}:${value}px;`),
  ...ds.spacing.map(value=>`--space-${value}:${value}px;`),
  ...Object.entries(ds.elevation).map(([name,value])=>`--shadow-${name}:${value};`),
  ...Object.entries(ds.radii).map(([name,value])=>`--radius-${name}:${value}px;`),
  '--radius-panel:var(--radius-card);', '--radius:12px;',
  ...Object.entries(ds.colors).map(([name,value])=>`--${name}:${value};`),
]
const mobileValues = Object.entries(ds.typography).filter(([,type])=>'mobileSize' in type).flatMap(([name,type])=>[`--text-${name}:${type.mobileSize}px;`,`--leading-${name}:${type.mobileLineHeight}px;`])
const css = `/* Generated by scripts/generate-ds.mjs. Source: src/design-system/registry.ts. */\n${fontFaces}\n:root{${rootValues.join('')}}\n@media(max-width:620px){:root{${mobileValues.join('')}}}\n`
const prefix = 'http://127.0.0.1:5173/r/'
const slug=name=>name.replace(/([a-z0-9])([A-Z])/g,'$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g,'$1-$2').toLowerCase()
const unique=ds.components.filter((component,index,array)=>array.findIndex(c=>c.file===component.file)===index)
const items = await Promise.all(unique.map(async component=>{
  const source=await readFile(path.join(root,component.file),'utf8')
  const imports=[...source.matchAll(/from\s+['"]([^'"]+)['"]/g)].map(match=>match[1])
  const dependencies=[...new Set(imports.filter(from=>!from.startsWith('.')&&!from.startsWith('@/')).map(from=>from.startsWith('@')?from.split('/').slice(0,2).join('/'):from.split('/')[0]))].filter(dep=>dep!=='react')
  const registryDependencies=[...new Set(imports.filter(from=>from.startsWith('.')||from.startsWith('@/')).map(from=>from.startsWith('@/')?'src/'+from.slice(2):path.posix.normalize(path.posix.join(path.posix.dirname(component.file),from))).map(file=>unique.find(c=>c.file===file+'.tsx')).filter(c=>c&&c.file!==component.file).map(c=>`${prefix}${slug(c.name)}.json`))]
  return {name:slug(component.name),type:component.kind==='ui'?'registry:ui':'registry:component',title:component.name,description:component.role,dependencies,registryDependencies,files:[{path:component.file,type:component.kind==='ui'?'registry:ui':'registry:component',target:component.file.replace('src/','')}]}
}))
const foundation={name:'case-ui',type:'registry:style',title:'Case UI foundation',description:'API, tokens, estilos e contrato do DS local.',dependencies:['@fontsource-variable/nunito-sans','@fontsource-variable/geist','@fontsource-variable/inter','@fontsource/ibm-plex-sans'],registryDependencies:items.filter(i=>i.name!=='stack').map(i=>`${prefix}${i.name}.json`),files:[
  'src/design-system/index.ts','src/design-system/registry.ts','src/design-system/layout.tsx','src/generated/ds-tokens.css','src/tokens.css','DS_CONTRACT.md',
].map(file=>({path:file,type:'registry:file',target:file.replace('src/','')}))}
const registry={$schema:'https://ui.shadcn.com/schema/registry.json',name:ds.name,homepage:'http://127.0.0.1:5173/design-system.html',items:[foundation,...items]}
const contract = await readFile(path.join(root,'DS_CONTRACT.md'),'utf8')
const api={schemaVersion:1,...ds,contract:'/api/DS_CONTRACT.md',registry:'/registry.json',components:ds.components.map(c=>({...c,importFrom:'@/design-system'}))}
const artifacts=[
  ['src/generated/ds-tokens.css',css],
  ['registry.json',JSON.stringify(registry,null,2)+'\n'],
  ['public/registry.json',JSON.stringify(registry,null,2)+'\n'],
  ['public/api/design-system.json',JSON.stringify(api,null,2)+'\n'],
  ['public/api/DS_CONTRACT.md',contract],
]
let failures=0
for(const [file,content] of artifacts){const full=path.join(root,file);if(checking){const current=await readFile(full,'utf8').catch(()=>null);if(current!==content){console.error(`Desatualizado: ${file}`);failures++}}else{await mkdir(path.dirname(full),{recursive:true});await writeFile(full,content)}}
if(failures)process.exit(1)
console.log(checking?'DS generated and registry synchronized.':`DS ${ds.version}: CSS, registry and API generated.`)
